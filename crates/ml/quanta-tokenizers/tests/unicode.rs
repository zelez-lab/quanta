#[test]
fn normalization_spot_checks() {
    // Composed <-> decomposed round trips.
    assert_eq!(nfd("café"), "cafe\u{301}");
    assert_eq!(nfc("cafe\u{301}"), "café");
    assert_eq!(nfc("e\u{301}"), "é");
    // Canonical ordering sorts marks by combining class (220 before 230).
    assert_eq!(nfd("a\u{301}\u{316}"), "a\u{316}\u{301}");
    // Hangul is algorithmic in both directions (LV and LVT syllables).
    assert_eq!(nfd("한"), "\u{1112}\u{1161}\u{11AB}");
    assert_eq!(nfc("\u{1112}\u{1161}\u{11AB}"), "한");
    assert_eq!(nfd("가"), "\u{1100}\u{1161}");
    assert_eq!(nfc("\u{1100}\u{1161}"), "가");
    assert_eq!(nfc(&nfd("각국")), "각국");
    // Composition exclusions stay decomposed under NFC.
    assert_eq!(nfd("\u{958}"), "\u{915}\u{93C}");
    assert_eq!(nfc(&nfd("\u{958}")), "\u{915}\u{93C}");
    // Singleton decompositions compose to the canonical char.
    assert_eq!(nfc("\u{212B}"), "\u{C5}"); // ANGSTROM SIGN -> Å
    assert_eq!(nfc("\u{2126}"), "\u{3A9}"); // OHM SIGN -> Ω
    // U+0344 is a non-starter decomposition (excluded).
    assert_eq!(nfd("\u{344}"), "\u{308}\u{301}");
    assert_eq!(nfc("a\u{344}"), "\u{E4}\u{301}");
    // Compatibility folds.
    assert_eq!(nfkc("ﬁ"), "fi");
    assert_eq!(nfkd("①"), "1");
    assert_eq!(nfkc("㎡"), "m2");
    assert_eq!(nfkc("ｶ"), "カ");
    assert_eq!(nfkc("²"), "2");
    let sallallahou = nfkd("\u{FDFA}");
    assert_eq!(sallallahou.chars().count(), 18);
    assert_eq!(sallallahou, "صلى الله عليه وسلم");
    // NFC/NFD leave compatibility characters alone.
    assert_eq!(nfc("ﬁ①㎡"), "ﬁ①㎡");
    // Idempotence.
    for s in ["café", "각", "ﬁ", "a\u{316}\u{301}\u{344}"] {
        assert_eq!(nfc(&nfc(s)), nfc(s));
        assert_eq!(nfd(&nfd(s)), nfd(s));
        assert_eq!(nfkc(&nfkc(s)), nfkc(s));
        assert_eq!(nfkd(&nfkd(s)), nfkd(s));
    }
}

