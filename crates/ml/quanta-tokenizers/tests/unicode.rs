/// Encodes a darts-clone unit: label in bits 0-7, has-leaf in bit 8,
/// offset in bits 10.. (extend bit 9 unused for these small tries).
fn unit(label: u8, has_leaf: bool, offset: usize) -> u32 {
    assert!(offset < (1 << 21), "offset must leave bit 31 clear");
    ((offset as u32) << 10) | (u32::from(has_leaf) << 8) | u32::from(label)
}

struct TrieBuilder {
    units: Vec<u32>,
    used: Vec<bool>,
}

impl TrieBuilder {
    fn new(len: usize) -> Self {
        TrieBuilder {
            units: vec![0; len],
            used: vec![false; len],
        }
    }

    fn set(&mut self, slot: usize, u: u32) {
        assert!(!self.used[slot], "slot collision at {slot}");
        self.used[slot] = true;
        self.units[slot] = u;
    }

    fn blob(&self, pool: &[u8]) -> Vec<u8> {
        let mut out = Vec::new();
        out.extend_from_slice(&(u32::try_from(self.units.len() * 4).unwrap()).to_le_bytes());
        for &u in &self.units {
            out.extend_from_slice(&u.to_le_bytes());
        }
        out.extend_from_slice(pool);
        out
    }
}

/// Pool: offset 0 "x", 2 "E", 4 "が", 8 "B!".
const SAMPLE_POOL: &[u8] = b"x\0E\0\xE3\x81\x8C\0B!\0";

/// Keys: "A"->"x", "B"->"B!", "BC"->"x", "e\u{301}"->"E",
/// "か\u{3099}"->"が" (the last is exactly 6 UTF-8 bytes).
fn sample_trie() -> TrieBuilder {
    let mut t = TrieBuilder::new(1024);
    t.set(0, unit(0, false, 256)); // root, base 256
    // "A" = [0x41]: leaf, value at slot 700.
    t.set(256 ^ 0x41, unit(0x41, true, (256 ^ 0x41) ^ 700));
    t.set(700, 0);
    // "B" = [0x42]: leaf (value at its own base, 96) with child 'C'.
    t.set(256 ^ 0x42, unit(0x42, true, (256 ^ 0x42) ^ 96));
    t.set(96, 8);
    // "BC": leaf, value at slot 800 — points at "x" to prove the walker
    // returns the *shortest* prefix hit ("B") like the reference.
    t.set(96 ^ 0x43, unit(0x43, true, (96 ^ 0x43) ^ 800));
    t.set(800, 0);
    // "e\u{301}" = [0x65, 0xCC, 0x81]: leaf at the end, value at 900.
    t.set(256 ^ 0x65, unit(0x65, false, (256 ^ 0x65) ^ 512));
    t.set(512 ^ 0xCC, unit(0xCC, false, (512 ^ 0xCC) ^ 64));
    t.set(64 ^ 0x81, unit(0x81, true, (64 ^ 0x81) ^ 900));
    t.set(900, 2);
    // "か\u{3099}" = [0xE3,0x81,0x8B,0xE3,0x82,0x99]: leaf at the end,
    // value at 1000. Intermediate nodes are not leaves.
    t.set(256 ^ 0xE3, unit(0xE3, false, (256 ^ 0xE3) ^ 40));
    t.set(40 ^ 0x81, unit(0x81, false, (40 ^ 0x81) ^ 576));
    t.set(576 ^ 0x8B, unit(0x8B, false, (576 ^ 0x8B) ^ 32));
    t.set(32 ^ 0xE3, unit(0xE3, false, (32 ^ 0xE3) ^ 968));
    t.set(968 ^ 0x82, unit(0x82, false, (968 ^ 0x82) ^ 16));
    t.set(16 ^ 0x99, unit(0x99, true, (16 ^ 0x99) ^ 1000));
    t.set(1000, 4);
    t
}

#[test]
fn charsmap_lookups_and_transform() {
    let cm = Charsmap::parse(&sample_trie().blob(SAMPLE_POOL)).unwrap();

    assert_eq!(cm.transform_chunk("A"), Some("x"));
    assert_eq!(cm.transform_chunk("AB"), Some("x")); // prefix hit
    assert_eq!(cm.transform_chunk("B"), Some("B!"));
    // Reference quirk: results[0] — the SHORTEST prefix wins, so "BC"
    // resolves through "B", not through its own leaf.
    assert_eq!(cm.transform_chunk("BC"), Some("B!"));
    assert_eq!(cm.transform_chunk("C"), None);
    assert_eq!(cm.transform_chunk("e\u{301}"), Some("E"));
    assert_eq!(cm.transform_chunk("か\u{3099}"), Some("が"));

    assert_eq!(cm.transform("A cat"), "x cat");
    // "e\u{301}" is a 3-byte grapheme: the whole-cluster window applies.
    assert_eq!(cm.transform("Ze\u{301}!"), "ZE!");
    // "か\u{3099}" is a 6-byte grapheme: the reference only tries whole
    // clusters under 6 bytes, so the entry must NOT fire through
    // `transform` even though `transform_chunk` matches it.
    assert_eq!(cm.transform("か\u{3099}"), "か\u{3099}");
    // Per-cluster misses pass through unchanged.
    assert_eq!(cm.transform("xBCy"), "xB!Cy");
    // A NUL input byte terminates the trie walk (reference semantics) and
    // the char passes through.
    assert_eq!(cm.transform("\0A"), "\0x");
    assert_eq!(cm.transform(""), "");
}

#[test]
fn charsmap_parse_errors() {
    // Truncated header.
    for len in 0..4 {
        let err = Charsmap::parse(&vec![1u8; len]).unwrap_err();
        assert_eq!(err.at, len);
        assert!(err.what.contains("truncated header"), "{err}");
    }
    // Trie length not a multiple of 4.
    let err = Charsmap::parse(&[6, 0, 0, 0, 0, 0, 0, 0, 0, 0]).unwrap_err();
    assert!(err.what.contains("multiple of 4"), "{err}");
    // Trie length past the end of the blob.
    let err = Charsmap::parse(&[8, 0, 0, 0, 0, 0, 0, 0]).unwrap_err();
    assert!(err.what.contains("exceeds"), "{err}");
    // Replacement pool must be UTF-8; the offset names the bad byte.
    let err = Charsmap::parse(&[0, 0, 0, 0, b'o', b'k', 0xFF]).unwrap_err();
    assert_eq!(err.at, 6);
    assert!(err.what.contains("UTF-8"), "{err}");
    // The Display shape carries the offset (the §8 message contract).
    assert_eq!(
        err.to_string(),
        "malformed precompiled charsmap at byte 6: replacement pool is not valid UTF-8"
    );
}

#[test]
fn charsmap_hostile_blobs_degrade_to_misses() {
    // Empty trie: parses, transforms are the identity.
    let cm = Charsmap::parse(&[0, 0, 0, 0]).unwrap();
    assert_eq!(cm.transform("abc é"), "abc é");
    assert_eq!(cm.transform_chunk("a"), None);

    // Root offset pointing far out of bounds: every walk misses.
    let mut t = TrieBuilder::new(4);
    t.set(0, unit(0, false, 1 << 20));
    let cm = Charsmap::parse(&t.blob(b"")).unwrap();
    assert_eq!(cm.transform("abc"), "abc");

    // Cyclic trie: a node whose offset points back at itself. The XOR
    // walk consumes one input byte per step, so it terminates regardless
    // of graph shape — a crafted blob cannot make a lookup spin.
    let mut t = TrieBuilder::new(256);
    t.set(0, unit(0, false, 0));
    t.set(0x61, unit(0x61, false, 0)); // 'a' loops to base 0x61
    let cm = Charsmap::parse(&t.blob(b"loop\0")).unwrap();
    assert_eq!(cm.transform_chunk(&"a".repeat(4096)), None);
    assert_eq!(cm.transform("aaaa"), "aaaa");

    // Leaf whose value slot is out of bounds: the hit is refused.
    let mut t = TrieBuilder::new(1024);
    t.set(0, unit(0, false, 256));
    t.set(256 ^ 0x41, unit(0x41, true, (256 ^ 0x41) ^ 2000));
    let cm = Charsmap::parse(&t.blob(SAMPLE_POOL)).unwrap();
    assert_eq!(cm.transform_chunk("A"), None);
    assert_eq!(cm.transform("A"), "A");

    // Value pointing past the pool: refused, char passes through.
    let mut t = sample_trie();
    t.units[700] = 999;
    let cm = Charsmap::parse(&t.blob(SAMPLE_POOL)).unwrap();
    assert_eq!(cm.transform_chunk("A"), None);
    assert_eq!(cm.transform("A"), "A");

    // Value landing inside a multi-byte char: refused (no panic, unlike a
    // naive slice).
    let mut t = sample_trie();
    t.units[700] = 1;
    let cm = Charsmap::parse(&t.blob(b"\xC3\xA9\0")).unwrap();
    assert_eq!(cm.transform_chunk("A"), None);

    // Unterminated pool tail: the replacement runs to the end of the pool.
    let mut t = sample_trie();
    t.units[700] = 0;
    let cm = Charsmap::parse(&t.blob(b"zz")).unwrap();
    assert_eq!(cm.transform_chunk("A"), Some("zz"));
}
